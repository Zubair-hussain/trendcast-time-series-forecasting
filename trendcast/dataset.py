"""
Original synthetic dataset for TrendCast.

This generates a reproducible, fully synthetic multi-series "engagement trends"
dataset. Because it is generated by this code, the dataset is 100% original and
can be redistributed under this project's MIT license with no third-party claims.

Each series simulates a content/topic's daily engagement with one of four
archetypes: viral spike, slow burn, seasonal, and fad-and-fade. Noise, weekly
seasonality and a random walk are layered on so models cannot trivially win.
"""

from __future__ import annotations

import csv
import os
from dataclasses import dataclass

import numpy as np

ARCHETYPES = ("viral_spike", "slow_burn", "seasonal", "fad_fade")


@dataclass
class Series:
    series_id: str
    archetype: str
    values: np.ndarray


def _one_series(rng: np.random.Generator, n: int, archetype: str) -> np.ndarray:
    t = np.arange(n)
    weekly = 1.0 + 0.15 * np.sin(2 * np.pi * t / 7.0)

    if archetype == "viral_spike":
        peak = rng.integers(n // 4, n // 2)
        base = 20 + 480 * np.exp(-((t - peak) ** 2) / (2 * (n * 0.08) ** 2))
    elif archetype == "slow_burn":
        base = 15 + 2.2 * t * (1 + 0.1 * rng.standard_normal())
    elif archetype == "seasonal":
        base = 120 + 70 * np.sin(2 * np.pi * t / 30.0) + 0.3 * t
    else:  # fad_fade
        rise = np.clip(t, 0, n // 3)
        base = 10 + 12 * rise - 6 * np.clip(t - n // 3, 0, None)
        base = np.clip(base, 5, None)

    walk = np.cumsum(rng.standard_normal(n)) * 0.8
    noise = rng.standard_normal(n) * (0.03 * base + 1.5)
    series = np.clip(base * weekly + walk + noise, 0, None)
    return np.round(series, 2)


def generate_dataset(
    n_series: int = 40,
    length: int = 120,
    seed: int = 20260101,
) -> list[Series]:
    """Deterministically generate a list of Series."""
    rng = np.random.default_rng(seed)
    out: list[Series] = []
    for i in range(n_series):
        arch = ARCHETYPES[i % len(ARCHETYPES)]
        vals = _one_series(rng, length, arch)
        out.append(Series(series_id=f"topic_{i:03d}", archetype=arch, values=vals))
    return out


def save_csv(series: list[Series], path: str) -> None:
    """Long format: series_id, archetype, day, value."""
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["series_id", "archetype", "day", "value"])
        for s in series:
            for day, v in enumerate(s.values):
                w.writerow([s.series_id, s.archetype, day, v])


def load_dataset(path: str) -> dict[str, np.ndarray]:
    """Load the long-format CSV back into {series_id: values}."""
    buckets: dict[str, list[tuple[int, float]]] = {}
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            buckets.setdefault(row["series_id"], []).append(
                (int(row["day"]), float(row["value"]))
            )
    return {
        sid: np.asarray([v for _, v in sorted(rows)], dtype=float)
        for sid, rows in buckets.items()
    }


if __name__ == "__main__":
    data = generate_dataset()
    save_csv(data, "data/trends_dataset.csv")
    print(f"wrote {len(data)} series to data/trends_dataset.csv")
